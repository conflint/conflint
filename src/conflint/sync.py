"""``confl sync`` - regenerate an accurate ``.env.example``.

Existing example files are treated as the source of truth for *comments,
ordering and blank lines*; the key set itself is authoritative from the
reconciled model.  Keys that no longer exist are dropped, new keys are appended
with an empty value, and secrets never get a value written.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Set

from conflint.config import Settings
from conflint.models import Config
from conflint.utils import read_text

__all__ = ["build_example", "default_example_file", "HEADER"]

HEADER = "# Generated by `confl sync`. Copy to .env and fill in real values.\n"

_ASSIGN = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=")


@dataclass
class _ExistingExample:
    """Snapshot of the current example file (if any) for lossless rewriting."""

    lines: Dict[str, str] = field(default_factory=dict)
    keys: Set[str] = field(default_factory=set)
    leading: List[str] = field(default_factory=list)


def default_example_file(root: Path, settings: Settings) -> Path:
    for name in settings.example_files:
        candidate = root / name
        if candidate.is_file():
            return candidate
    return root / ".env.example"


def build_example(model: Config, settings: Settings) -> str:
    """Render the content of an example file for ``model``."""

    existing = _load_existing(model.root, settings)
    keys = _required_keys(model, settings)

    output: List[str] = []

    # Preserve the leading comment block of the existing file.
    output.extend(existing.leading)

    emitted = 0
    for key in keys:
        if existing.lines.get(key):
            output.append(existing.lines[key])
        else:
            output.append(f"{key}=")
        emitted += 1

    # Drop genuinely stale keys (present in the old file, required by nothing).
    stale = sorted(existing.keys - set(keys))
    if stale:
        output.append("")
        output.append("# Removed by `confl sync` (no longer referenced anywhere):")
        output.extend(f"# {key}" for key in stale)

    if emitted == 0 and not stale:
        output.append("")

    return "\n".join(output) + "\n"


def _load_existing(root: Path, settings: Settings) -> _ExistingExample:
    path = default_example_file(root, settings)
    if not path.is_file():
        return _ExistingExample(leading=[HEADER.rstrip("\n")])

    text = read_text(path)
    lines = text.splitlines()
    existing = _ExistingExample()
    for line in lines:
        match = _ASSIGN.match(line)
        if match:
            key = match.group(1)
            existing.keys.add(key)
            existing.lines[key] = line
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped and stripped.startswith("export"):
            existing.leading.append(line)
        elif "=" in stripped:
            break
        else:
            existing.leading.append(line)
    if not existing.leading:
        existing.leading = [HEADER.rstrip("\n")]
    return existing


def _required_keys(model: Config, settings: Settings) -> List[str]:
    """Deterministic order: read in code first, then provided but unread names."""

    seen: Set[str] = set()
    required: List[str] = []
    for usage in model.usages:
        if settings.is_name_ignored(usage.name):
            continue
        if usage.name not in seen:
            seen.add(usage.name)
            required.append(usage.name)
    for entry in model.entries:
        if entry.is_example or settings.is_name_ignored(entry.name):
            continue
        if entry.name not in seen:
            seen.add(entry.name)
            required.append(entry.name)
    return required